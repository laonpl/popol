/** These are editing cues, not a keyword-based acceptance test. */
export function coverLetterWritingGuide(question = '', limits = {}) {
  const text = String(question);
  const length = Number(limits.maxLength || limits.minLength || 700);
  const paragraphs = length <= 300 ? '1~2개' : length <= 800 ? '2~3개' : '3~5개';
  const motivation = /지원[\s\S]{0,35}(?:동기|이유)|지원동기/.test(text);
  const growth = /입사\s*후|전문가로\s*성장|성장[\s\S]{0,30}노력/.test(text);
  const cues = [
    '문항을 서로 다른 필수 요구로 나누고, 각 요구에 직접 답하는 내용을 본문에 배치하세요. 주제 단어나 기업명만 등장하는 것은 답변이 아닙니다.',
    '문항에 맞는 구성을 선택하세요. 모든 질문을 경험 소개→성과→포부라는 같은 틀로 쓰지 마세요. 경험은 질문에 대한 답을 뒷받침하는 데 필요한 만큼만 쓰세요.',
    '한 문장에 한 가지 생각을 담고 앞 문장의 판단과 다음 행동이 이어지게 쓰세요. 명사·기술명 나열, 긴 관형절, 번역투와 같은 결론의 반복을 줄이세요. 지원자가 면접에서 자기 말로 설명할 수 있는 표현을 쓰세요.',
    `본문은 의미가 이어지는 ${paragraphs} 문단으로 구성하세요. 650~700자 분량은 대체로 3문단이 읽기 좋습니다. 한 문단에는 하나의 중심 내용만 담고, 지원 이유·근거 경험·향후 계획처럼 이야기의 초점이 바뀌는 곳에서 나누세요.`,
    '문단 사이는 빈 줄 하나(줄바꿈 두 번)로 구분하세요. 문장마다 줄을 바꾸거나 문단 앞에 들여쓰기·제목·번호·불릿을 붙이지 마세요. 문단 구분을 위한 줄바꿈도 지정된 글자 수 계산에 포함해 분량을 맞추세요. 공백 제외 설정이면 줄바꿈은 세지 않습니다.',
  ];
  if (motivation) cues.push(
    '지원동기는 확인된 기업·직무의 특징과 본인이 중요하게 보는 업무 기준이 어떻게 맞는지 설명하세요. 회사 소개나 비전에 공감한다는 말로 대신하지 마세요. 회사명을 다른 곳으로 바꿔도 성립하는 찬사는 삭제하세요.',
    '기업 선택 이유와 직무 선택 이유를 함께 물으면 두 이유를 구분해 답하세요. 관련 경험 하나에서 실제로 한 판단·행동을 근거로 연결하고 프로젝트 기술 스택 소개로 본문을 채우지 마세요.',
  );
  if (growth) cues.push(
    '성장 노력은 무엇을 보완할지→어떤 방식으로 연습·적용할지→무엇을 점검해 개선할지로 구체화하세요. “심화 학습”, “끊임없이 도전”, “지식 공유”, “가치 극대화”만으로 계획을 대신하지 마세요. 문항·직무와 맞는 실행 한두 가지를 충분히 설명하세요.',
    '입사 후 계획은 앞으로 하려는 행동으로 제안할 수 있습니다. 원문에 없는 과거 경험·보유 역량·성과를 만들거나, 확인되지 않은 회사 내부 제도·기술 환경을 확정해 쓰지 마세요.',
  );
  if (motivation && growth) cues.push(
    '이 문항의 중심은 기업·직무 지원 이유와 전문가가 되기 위한 구체적인 노력입니다. 경험 소개는 이유의 근거로 압축하고, 본문 후반에는 실행 방법과 점검 방법을 남기세요. 마지막에 추상적인 포부를 덧붙여 같은 말을 반복하지 마세요.',
  );
  return cues.map(cue => `- ${cue}`).join('\n');
}

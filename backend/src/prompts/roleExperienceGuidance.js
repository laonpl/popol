export const roleInterviewGuidance = role => guides[role] || '';
export const roleFollowUpQuestions = role => questions[role] ? [...questions[role]] : null;

export function roleMomentGuidance(role) {
  if (!guides[role]) return '';
  const focus = role === 'pm'
    ? '고객 관찰→문제 정의→대안과 MVP 범위 결정→서비스 흐름·정책·인수 기준→출시/검증→바뀐 판단을 하나의 제품 의사결정 사례로 묶는다. 구현 기술이나 기능 개수 대신 무엇을 왜 선택·제외했고 본인이 어떤 정책을 정했는지 보존한다.'
    : '고객/타깃 관찰→메시지와 실제 소재 문안→채널·CRM 운영→반응/측정→개선 선택을 하나의 캠페인·콘텐츠·고객 관계 사례로 묶는다. 콘텐츠 제작량만 남기지 말고 실제 후킹 문구·CTA, 채널 선택 이유, 반응 후 바꾼 실행을 보존한다.';
  return `[${role === 'pm' ? '기획/PM' : '마케터'} 핵심 경험 추출]\n${focus}
같은 프로젝트에서도 원문에 적힌 해당 직군의 직접 판단과 기여를 중심으로 title/context/action/result/learning을 작성한다. 팀의 코드 구현·아키텍처·성능 개선을 자동으로 본인의 직군 경험으로 바꾸지 않는다.
직군과 관련된 행동이 원문에 없으면 억지로 재해석하지 않는다. 출시 전 설계, 실패·중단, 정성 반응도 기록된 사실이면 유효하다. 계획·목표를 실행·실측으로 바꾸지 않는다.
실제 판단 사례가 하나면 하나만 반환한다. 한 캠페인이나 제품 문제의 단계를 여러 경험으로 쪼개 개수를 채우지 않는다.`;
}
